create or replace function public.submit_shop_secure(
  p_shop_name text,p_kp text,p_location text,p_latitude double precision,p_longitude double precision,
  p_agent_name text,p_phone text,p_whatsapp text,p_alternative text,p_visit_date date,
  p_is_selling boolean,p_needs_machine boolean,p_photo1 text,p_photo2 text,p_device_info jsonb
) returns uuid
language plpgsql security definer set search_path=public as $$
declare x uuid;
begin
  if trim(coalesce(p_kp,'')) <> '' then
    if exists(select 1 from public.shop_submissions where lower(trim(kp))=lower(trim(p_kp)) and lower(trim(shop_name))=lower(trim(p_shop_name))) then
      raise exception 'Duplicate KP and shop name';
    end if;
  end if;
  insert into public.shop_submissions(
    shop_name,kp,location,latitude,longitude,agent_name,phone_number,whatsapp_number,alternative_number,
    visit_date,is_selling,needs_machine,photo1_path,photo2_path,created_by
  ) values (
    trim(p_shop_name),nullif(trim(p_kp),''),trim(p_location),p_latitude,p_longitude,trim(p_agent_name),trim(p_phone),
    nullif(trim(p_whatsapp),''),nullif(trim(p_alternative),''),p_visit_date,p_is_selling,p_needs_machine,
    nullif(trim(p_photo1),''),nullif(trim(p_photo2),''),null
  ) returning id into x;
  insert into public.security_events(event_type,ip,ip_hash,user_agent,metadata)
  values('shop_submission',(p_device_info->>'ip')::inet,p_device_info->>'ip_hash',p_device_info->>'user_agent',jsonb_build_object('shop_id',x,'kp',nullif(trim(p_kp),'')));
  return x;
end$$;

revoke all on function public.submit_shop_secure(text,text,text,double precision,double precision,text,text,text,text,date,boolean,boolean,text,text,jsonb) from public;
grant execute on function public.submit_shop_secure(text,text,text,double precision,double precision,text,text,text,text,date,boolean,boolean,text,text,jsonb) to anon,authenticated;

drop view if exists public.shop_location_analysis;
create or replace view public.shop_location_analysis as
select location,count(*) total_shops,count(*) filter(where is_selling) selling_shops,count(*) filter(where not is_selling) not_selling_shops,count(*) filter(where needs_machine) needs_machine,count(*) filter(where not needs_machine) has_machine
from public.shop_submissions group by location order by total_shops desc;

