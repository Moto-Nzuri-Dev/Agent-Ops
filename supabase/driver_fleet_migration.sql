-- Moto Nzuri v3.2 driver/fleet migration
-- Run this entire file in Supabase SQL Editor if the four driver/fleet tables are missing.
create extension if not exists pg_trgm;

create table if not exists public.admin_allowlist (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  created_at timestamptz default now()
);

create table if not exists public.driver_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  full_name text not null,
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  registration_number text unique not null,
  vehicle_name text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  current_odometer numeric(12,2)
);

create table if not exists public.driver_vehicle_assignments (
  driver_id uuid primary key references public.driver_profiles(user_id) on delete cascade,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  assigned_at timestamptz not null default now()
);

create table if not exists public.vehicle_odometer_logs (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null references public.driver_profiles(user_id) on delete cascade,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  odometer numeric(12,2) not null check(odometer >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.vehicle_problems (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null references public.driver_profiles(user_id) on delete cascade,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  odometer numeric(12,2),
  problem text not null check(length(trim(problem)) between 2 and 1000),
  issue_resolved boolean not null default false,
  comments text,
  created_at timestamptz not null default now()
);

create table if not exists public.machine_fuel_logs (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null references public.driver_profiles(user_id) on delete cascade,
  timestamp timestamptz not null default now(),
  log_date date not null default current_date,
  shop_name text not null check(length(trim(shop_name)) between 2 and 120),
  latitude double precision not null check(latitude between -90 and 90),
  longitude double precision not null check(longitude between -180 and 180),
  machine_number text not null check(length(trim(machine_number)) between 1 and 100),
  kp_number text,
  fuel_pumped numeric(12,2) not null check(fuel_pumped >= 0),
  display_photo_path text,
  email_address text not null,
  machine_calibrated boolean not null,
  refill_type text not null default 'custom' check(refill_type in ('first_refill','second_refill','custom')),
  comments text,
  created_at timestamptz not null default now()
);

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  user_id uuid,
  ip inet,
  ip_hash text,
  user_agent text,
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz default now()
);

create table if not exists public.shop_submissions (
  id uuid primary key default gen_random_uuid(),
  shop_name text not null check(length(trim(shop_name)) between 2 and 120),
  kp text check(kp is null or length(trim(kp)) between 1 and 80),
  location text not null check(length(trim(location)) between 2 and 120),
  latitude double precision not null check(latitude between -90 and 90),
  longitude double precision not null check(longitude between -180 and 180),
  agent_name text not null check(length(trim(agent_name)) between 2 and 120),
  phone_number text not null,
  whatsapp_number text,
  alternative_number text,
  visit_date date not null,
  is_selling boolean not null,
  needs_machine boolean not null,
  photo1_path text,
  photo2_path text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  search_document tsvector generated always as (to_tsvector('simple',coalesce(shop_name,'')||' '||coalesce(kp,'')||' '||coalesce(location,'')||' '||coalesce(agent_name,'')||' '||coalesce(phone_number,'')||' '||coalesce(whatsapp_number,'')||' '||coalesce(alternative_number,''))) stored
);

