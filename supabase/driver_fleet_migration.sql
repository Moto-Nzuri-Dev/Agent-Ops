create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.admin_allowlist where user_id=auth.uid())
$$;

create or replace function public.is_driver() returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.driver_profiles where user_id=auth.uid() and active)
$$;

