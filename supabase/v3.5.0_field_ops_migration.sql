create extension if not exists pgcrypto;
create extension if not exists pg_trgm;

alter table public.agent_representative_submissions
  add column if not exists location text,
  add column if not exists till_number text,
  add column if not exists is_selling boolean not null default false,
  add column if not exists canisters_delivered integer not null default 0;

alter table public.agent_representative_submissions
  drop constraint if exists agent_representative_submissions_canisters_delivered_check;
alter table public.agent_representative_submissions
  add constraint agent_representative_submissions_canisters_delivered_check
  check (canisters_delivered >= 0 and canisters_delivered <= 100000);

create index if not exists idx_rep_submission_search on public.agent_representative_submissions
  using gin (to_tsvector('simple',
    coalesce(shop_name,'') || ' ' || coalesce(location,'') || ' ' || coalesce(till_number,'') || ' ' ||
    coalesce(agent_name,'') || ' ' || coalesce(mpesa_number,'') || ' ' ||
    coalesce(representative_email,'')
  ));
create index if not exists idx_rep_submission_location on public.agent_representative_submissions(latitude, longitude);
create unique index if not exists uq_rep_submission_till
  on public.agent_representative_submissions (till_number)
  where till_number is not null and trim(till_number) <> '';

create table if not exists public.technician_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  full_name text not null check (length(trim(full_name)) between 2 and 120),
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.technician_profiles enable row level security;
drop policy if exists admin_read_technician_profiles on public.technician_profiles;
create policy admin_read_technician_profiles on public.technician_profiles
  for select to authenticated using (public.is_admin());
drop policy if exists technician_own_profile on public.technician_profiles;
create policy technician_own_profile on public.technician_profiles
  for select to authenticated using (user_id = auth.uid() and active);

alter table public.customer_care_tickets
  add column if not exists assigned_representative_id uuid references public.agent_representative_profiles(user_id) on delete set null,
  add column if not exists assigned_technician_id uuid references public.technician_profiles(user_id) on delete set null,
  add column if not exists assigned_by uuid references auth.users(id) on delete set null,
  add column if not exists assigned_at timestamptz,
  add column if not exists verified_by uuid references auth.users(id) on delete set null,
  add column if not exists verified_at timestamptz,
  add column if not exists last_updated_by uuid references auth.users(id) on delete set null;

-- Expand the legacy customer-care status list for assignment and technician workflows.
alter table public.customer_care_tickets drop constraint if exists customer_care_tickets_status_check;
alter table public.customer_care_tickets
  add constraint customer_care_tickets_status_check
  check (status in ('Not resolved','Assigned','In progress','Resolved','Verified','Closed','On hold','Reopened'));

create index if not exists idx_tickets_assigned_rep on public.customer_care_tickets(assigned_representative_id, ticket_date desc);
create index if not exists idx_tickets_assigned_tech on public.customer_care_tickets(assigned_technician_id, ticket_date desc);
create index if not exists idx_tickets_master_search on public.customer_care_tickets
  using gin (to_tsvector('simple', coalesce(shop_name,'') || ' ' || coalesce(location,'') || ' ' ||
    coalesce(issue_category,'') || ' ' || coalesce(issue_description,'')));

create table if not exists public.ticket_activity (
  id bigint generated by default as identity primary key,
  ticket_id uuid not null references public.customer_care_tickets(id) on delete cascade,
  ticket_no bigint,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  old_values jsonb,
  new_values jsonb,
  created_at timestamptz not null default now()
);
alter table public.ticket_activity enable row level security;
drop policy if exists admin_read_ticket_activity on public.ticket_activity;
create policy admin_read_ticket_activity on public.ticket_activity
  for select to authenticated using (public.is_admin());

create or replace function public.audit_ticket_changes() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.ticket_activity(ticket_id,ticket_no,actor_id,action,new_values)
    values(new.id,new.ticket_no,new.created_by,'created',to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    if row(old.status,old.assigned_representative_id,old.assigned_technician_id,old.priority,old.resolution)
       is distinct from
       row(new.status,new.assigned_representative_id,new.assigned_technician_id,new.priority,new.resolution) then
      insert into public.ticket_activity(ticket_id,ticket_no,actor_id,action,old_values,new_values)
      values(new.id,new.ticket_no,coalesce(new.last_updated_by,new.created_by),'updated',
        jsonb_build_object('status',old.status,'assigned_representative_id',old.assigned_representative_id,
          'assigned_technician_id',old.assigned_technician_id,'priority',old.priority,'resolution',old.resolution),
        jsonb_build_object('status',new.status,'assigned_representative_id',new.assigned_representative_id,
          'assigned_technician_id',new.assigned_technician_id,'priority',new.priority,'resolution',new.resolution));
    end if;
    return new;
  end if;
  return new;
end $$;

drop trigger if exists trg_audit_ticket_changes on public.customer_care_tickets;
create trigger trg_audit_ticket_changes
after insert or update on public.customer_care_tickets
for each row execute function public.audit_ticket_changes();

