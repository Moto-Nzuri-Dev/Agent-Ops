-- Moto Nzuri Field Ops V3.6.0: Master shop seed, MN checklist, and representative updates.
-- Run in Supabase SQL Editor after V3.5.0 migration and before deploying this release.

create extension if not exists pg_trgm;

alter table public.agent_representative_submissions
  add column if not exists kp_number text,
  add column if not exists master_seed_no text,
  add column if not exists is_branded boolean not null default false,
  add column if not exists has_network boolean not null default false,
  add column if not exists has_paybill boolean not null default false,
  add column if not exists account_mn_number text,
  add column if not exists bank_account text,
  add column if not exists last_edited_at timestamptz,
  add column if not exists last_edited_by uuid references auth.users(id) on delete set null,
  add column if not exists edit_count integer not null default 0;

-- Till is optional. Drop the uniqueness rule and never use 000000 as a placeholder.
drop index if exists public.uq_rep_submission_till;

alter table public.agent_representative_submissions
  drop constraint if exists agent_representative_submissions_till_number_check;

create index if not exists idx_rep_submission_seed on public.agent_representative_submissions(master_seed_no);
create index if not exists idx_rep_submission_kp on public.agent_representative_submissions(kp_number);
create index if not exists idx_rep_submission_master_text on public.agent_representative_submissions
  using gin (to_tsvector('simple', coalesce(shop_name,'') || ' ' || coalesce(location,'') || ' ' ||
    coalesce(kp_number,'') || ' ' || coalesce(till_number,'') || ' ' || coalesce(agent_name,'') || ' ' ||
    coalesce(mpesa_number,'') || ' ' || coalesce(account_mn_number,'') || ' ' || coalesce(bank_account,'') || ' ' ||
    coalesce(representative_email,'')));

create table if not exists public.representative_shop_edit_history (
  id bigint generated by default as identity primary key,
  submission_id uuid not null references public.agent_representative_submissions(id) on delete cascade,
  representative_id uuid not null references auth.users(id) on delete cascade,
  edited_at timestamptz not null default now(),
  action text not null check (action in ('created','updated')),
  old_values jsonb,
  new_values jsonb
);
create index if not exists idx_rep_shop_history_submission on public.representative_shop_edit_history(submission_id, edited_at desc);
alter table public.representative_shop_edit_history enable row level security;
drop policy if exists admin_read_representative_shop_edit_history on public.representative_shop_edit_history;
create policy admin_read_representative_shop_edit_history on public.representative_shop_edit_history
  for select to authenticated using (public.is_admin());

-- All writes are performed by the server using the server-only Supabase secret.
-- Representative ownership is enforced by the server query: id + representative_id.
