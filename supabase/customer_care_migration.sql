-- Moto Nzuri Field Ops v3.4.0 - Customer Care ticketing
-- Run this migration once in Supabase SQL Editor. Existing operational tables are preserved.
create extension if not exists pgcrypto;

create table if not exists public.customer_care_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_no bigint generated by default as identity unique,
  ticket_date date not null default current_date,
  issue_source text not null default 'Agent' check (issue_source in ('Agent','Driver','Customer','Internal','Other')),
  reported_by text,
  shop_name text,
  location text,
  issue_category text,
  issue_description text not null,
  priority text not null default 'Medium' check (priority in ('Urgent','High','Medium','Low')),
  status text not null default 'Not resolved' check (status in ('Not resolved','In progress','Resolved')),
  resolution text,
  resolution_date date,
  csr_name text,
  month text not null default to_char(current_date, 'Mon'),
  quarter text not null default ('Q' || extract(quarter from current_date)::text),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists customer_care_tickets_date_idx on public.customer_care_tickets (ticket_date desc);
create index if not exists customer_care_tickets_status_idx on public.customer_care_tickets (status, priority);
create index if not exists customer_care_tickets_shop_idx on public.customer_care_tickets (lower(shop_name));

alter table public.customer_care_tickets enable row level security;
-- No client policies are granted. Access is through authenticated admin API routes using the server-only Supabase secret key.
